// Export monster templates as MONSTER_TEMPLATES for backward compatibility
export const MONSTER_TEMPLATES = monsterTemplates;

// Helper function to get monster by ID
export function getMonsterTemplate(id: string): MonsterTemplate | undefined {
  return monsterTemplates.find(m => m.id === id);
}

// Get monsters by element
export function getMonstersByElement(element: string): MonsterTemplate[] {
  return monsterTemplates.filter(m => m.element === element);
}

// Get monsters by rarity
export function getMonstersByRarity(rarity: string): MonsterTemplate[] {
  return monsterTemplates.filter(m => m.rarity === rarity);
}
